def main():
    if not os.path.exists(DB_PATH):
        print(f"DB 파일을 찾을 수 없습니다: {DB_PATH}")
        print("app.py를 먼저 한 번 실행하여 DB를 초기화하세요.")
        return

    conn = sqlite3.connect(DB_PATH)
    pw_hash = hash_pw('1234')

    # admin을 제외한 기존 사용자 전체 삭제
    deleted = conn.execute("DELETE FROM users WHERE username != 'admin'").rowcount
    print(f"기존 사용자 {deleted}명 삭제")

    # PDF 기준으로 재등록
    inserted = 0
    for username, name, part, role, hire_date in USERS:
        conn.execute(
            "INSERT INTO users (username, password, name, part, role, hire_date, retired_date)"
            " VALUES (?,?,?,?,?,?,?)",
            (username, pw_hash, name, part, role, hire_date, '')
        )
        inserted += 1

    conn.commit()
    conn.close()
    print(f"신규 등록 {inserted}명 완료 (초기 비밀번호: 1234)")

if __name__ == '__main__':
    main()
